/**
 * 온-디바이스 세션 스펙이 공유하는 **고정 대상 앱**.
 *
 * 왜 고정하는가: 이 스펙들은 원래 CLI 기본값(포그라운드 앱)을 그대로 썼다. 그래서
 * **사람이 화면에 무엇을 두었는가가 테스트의 결과를 정했다.** 실기기 5회 연속 실행에서
 * 그것이 두 가지 모양으로 드러났다.
 *
 *   1. 컨트롤러가 관측한 실패 — 포그라운드가 `com.android.settings` 라서 시스템 앱 경로를
 *      밟았고, 그때만 결함이 보였다. 같은 기기의 다른 순간에는 서드파티 앱이 포그라운드라
 *      같은 코드가 통과했다.
 *   2. 5회 연속 실행의 1·2회차 실패 — 폰이 홈 화면이라 포그라운드가
 *      `com.sec.android.app.launcher` 였다. 런처 자신에게는 런처 액티비티가 없어서
 *      (`cmd package resolve-activity … com.sec.android.app.launcher` → `No activity found`)
 *      `--launch` 가 거부됐다. 코드가 아니라 **폰이 어느 화면에 있었는가**가 원인이다.
 *
 * 왜 하필 이 앱:
 *   - 모든 안드로이드 빌드(AOSP·GSI·벤더·에뮬레이터)에 있다.
 *   - 런처 액티비티가 있다 (실기기 실측: `com.android.settings.Settings`).
 *   - **uid 1000 을 여럿이 공유한다** (실기기 실측 86개). M3 스펙이 가장 확인하고 싶은
 *     경로 — "이 숫자는 한 앱의 것이 아니다" — 를 실제로 밟는 유일한 선택이다.
 *   - 사용자의 개인 앱을 `am force-stop` 하지 않는다. 예전에는 화면에 떠 있던 앱이 무엇이든
 *     그것을 강제 종료했다.
 *
 * **단언을 무르게 하려고 고정한 것이 아니다.** "시스템 앱이면 건너뛴다" 는 갈래는 어디에도
 * 없고, 스펙의 단언은 대상이 무엇이든 똑같이 걸린다.
 *
 * 포그라운드 감지 자체는 `m0` 이 기기에서 따로 검증한다 — 세션을 열지 않고 이 기기의
 * `dumpsys window` 출력 형식에 파서가 맞는지만 본다.
 */
export const DEVICE_TARGET_APP = 'com.android.settings'
